# 시뮬레이션 설명 - 이 시뮬레이션이 무엇을 하고, 한 번 돌리면 어떤 결과가 나오는지 정리한 주석 파일 (실행 X)
#
# =====================================================================
# 1. 시뮬레이션이 하는 일
# =====================================================================
# 6x6 위성 Grid에서 출발 위성 (0,0)이 도착 위성 (5,5)로 패킷을 10분 동안 보내고,
# 라우팅이 혼잡을 얼마나 잘 피해 기한 안에 도착시키는지 측정함.
#
#   주요 설정: 1 step = 1 ms, 30초(30,000 step) 에피소드 x 20개 = 10분
#   주 흐름    : 1초에 60개 생성, 160 Byte, 기한 70 ms, TTL 20홉
#   링크       : 상/하 지연 7 step, 좌/우 지연 2 step, 1 step에 5개 전송, 링크별 큐 200개
#   배경 트래픽: 송신 큐 핫스팟 (위성 하나의 한 방향 큐가 과부하)
#                에피소드마다 시드(혼잡 지도)가 달라서 핫스팟 개수(2~5개), 위치, 세기(링크 용량의 0.7~2.0배)가 바뀜
#                짧게 켜졌다(평균 0.15초) 길게 꺼짐(평균 0.75초). 고정 경로라서 라우팅 대상이 아님
#   (값은 config_isl.py, 변수 설명은 variables_isl.py)
#
#   에피소드: 큐가 빈 상태로 시작하는 30초짜리 실행 한 판. 에피소드 e는 시작 시드 + e를 씀
#             -> 한 번 실행하면 혼잡 지도 20개를 겪고, 결과는 20개를 합친 값
#
# =====================================================================
# 2. 매 step(1 ms)마다 반복하는 순서
# =====================================================================
#   1) 도착        : 링크를 건너온 패킷의 홉 +1, TTL -1
#   2) 목적지 확인 : (5,5)면 기한 안/밖을 판정하고 끝
#   3) 중간 확인   : 기한이 지났거나 TTL이 0이면 손실
#   4) 생성        : 주 흐름 패킷과 배경 패킷 생성
#   5) 라우팅      : 주 흐름 패킷마다 route_A(최단 경로) 또는 route_B(부하 고려)가 다음 방향을 고름.
#                    (config_isl.py P.routeName으로 선택)
#                    큐가 꽉 찼으면 오버플로 손실. 결정은 매번 decision_log에 기록됨.
#   6) 전송        : 링크마다 큐 앞에서 최대 5개를 보냄
#
# 두 번 실행함
#   ε = 0   : route_B대로만                  -> 성능 측정용
#   ε = 0.1 : 10% 확률로 갈 수 있는 방향 중 하나를 무작위 선택 -> 강화학습 데이터 수집용
#
# =====================================================================
# 3. 한 번 돌리면 나오는 결과 (results 폴더)
# =====================================================================
# 파일                          1줄(1장) =          내용 / 용도
# metrics_summary.csv / .png    실행 1번            성능 지표 7개(평균 지연, 손실률, 처리량, 기한 내 도착률,
#                                                   최대 연속 손실, 경로 변경 수, 평균 홉 수)
#                                                   + 손실 원인별 개수 + 배경 개수 / 보고서, 비교
# packet_log_*.csv              패킷 1개            생성 시각, 끝난 시각, 결과(1 기한 내, 2 목적지 늦음,
#                                                   3 중간 늦음, 4 오버플로, 5 TTL), 홉 수 / 지연 분포, 시간대별 분석
# decision_log_*.csv (ε=0.1만)  라우팅 결정 1번     그 순간 위성 상태(큐, L, N, 남은 거리와 기한, TTL)
#                                                   + 고른 방향 + 선택 유형 + 큐 진입 여부 / 강화학습 학습 데이터
# node_log_*.csv                0.1초마다 노드 1개  노드별 큐 길이, 보낸 수, 오버플로, 기한 초과, 남은 기한 / 노드별 분석
# run_analysis.png              그림 1장            지연 분포, 시간별 변화, 링크 사용량 지도, 홉 수, 선택 유형,
#                                                   손실 원인 / 실행 분석
# node_map_*.png                그림 1장            6x6 노드별 요약 지도 / 혼잡한 노드 찾기
# node_time_*.png               그림 1장            손실이 가장 많은 노드의 시간 변화 / 혼잡 원인 보기
# anim_*.gif (ε=0만)            애니메이션          처음 0.2초 동안 링크 큐 색과 이동 중 패킷 / 발표, 설명용
#
# bg_scenario.csv               핫스팟 1개          에피소드별 핫스팟 위치, 방향, 세기 / 어떤 혼잡 지도였는지 확인
#
