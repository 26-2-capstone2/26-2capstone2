# =====================================================================
# 5. 여러 시드 실험 (run_experiments.py, 설정은 config_bg.py)
# =====================================================================
# 시드 하나의 결과는 "배경이 우연히 그렇게 켜졌을 때"의 한 경우라서,
# 부하 단계마다 시드 여러 개로 돌려 평균 ± 표준편차로 보고함.
#   평가 (B.runEval)        : ε = 0, 평가용 시드 101~110 -> results/experiments/
#                             eval_runs.csv (실행 1번 = 1줄), eval_stats.csv (단계별 평균·편차),
#                             eval_summary.png, conditions.txt (고정 조건 기록)
#   학습 데이터 (B.runTrain): ε = 0.1, 학습용 시드 1~10 -> results/experiments/train/
#                             decision_log_{단계}_seed{n}.csv, packet_log_{단계}_seed{n}.csv
# 학습용과 평가용 시드를 나눈 이유: RL이 처음 보는 혼잡 패턴에서도 잘해야 "외워서 잘한 게 아니다"라고 말할 수 있음
