% ISL 시뮬레이션 사용 안내
%
% =====================================================================
% 0. 시뮬레이션 베이스라인
% =====================================================================
% 6x6 Grid ISL 위성망에서 출발 위성 (0,0) -> 도착 위성 (5,5)로 패킷을 보내고,
% 라우팅(링크 혼잡도를 보고 다음 방향 선택)으로 경로를 정함.
% 결과로 성능 지표 7개, 애니메이션, 강화학습용 결정 기록을 만듦.
%
% =====================================================================
% 1. 시뮬레이션 돌리는 방법
% =====================================================================
% (1) MATLAB 실행
% (2) 이 폴더 열기 or 명령 창에  cd('폴더 경로') 입력
% (3) main_isl.m 을 열고, [편집기] 탭의 초록색 ▶ "실행" 버튼 클릭
%     또는 명령 창 입력:  main_isl
% (4) 약 3~4분 기다리기
%     명령 창에 아래 두 줄이 찍히고 결과 표가 나오면 끝
%       [rate60pps_eps0.0] ...   (성능 측정용 실행)
%       [rate60pps_eps0.1] ...   (강화학습 데이터 수집용 실행)
%       결과 저장 완료: ...
%
% =====================================================================
% 2. 결과 확인 방법
% =====================================================================
% 방법 1) MATLAB 창에서 보기
%   명령 창에 입력:  show_results
%   -> 지표 표(명령 창) + 지표 그래프 창 + 애니메이션 창이 뜸
%   -> 애니메이션은 창을 닫을 때까지 반복 재생
%
% 방법 2) 파일로 보기 (isl_6x6_routing\results 폴더 또는 아래 3번 저장 폴더)
%   metrics_summary.png               : 성능 지표 7개를 실행별 막대로 비교
%   run_analysis.png                  : 실행 분석 (지연 분포, 시간별 변화, 링크 사용량 지도, 홉 수, 선택 유형, 손실 원인)
%   metrics_summary.csv               : 성능 지표 숫자 (엑셀로 열림)
%   anim_rate60pps_eps0.0.gif         : 0~200 ms 애니메이션 (링크 색 = 큐가 찬 정도, 점 = 이동 중인 패킷)
%   packet_log_*.csv                  : 패킷 1개 = 1줄 (생성 시각, 도착 시각, 결과, 홉 수)
%   decision_log_rate60pps_eps0.1.csv : 라우팅 결정 1번 = 1줄 (강화학습 학습용 데이터)
%
%   결과 숫자(result) 의미: 1 기한 내 도착, 2 목적지 기한 초과, 3 중간 기한 초과, 4 큐 오버플로, 5 TTL 만료
%
% =====================================================================
% 3. 결과 저장 경로
% =====================================================================
% 시뮬레이션이 끝나면 자동으로 아래 폴더에 저장됨 (실행할 때마다 날짜_시분 폴더가 새로 생김)
%   C:\Users\eun\Desktop\capstone_isl\baseline\2026-10-04_1320\
%       code\     그때 사용한 .m 파일 전부 (어떤 설정으로 돌렸는지 확인용)
%       results\  이미지(.png, .gif) + CSV
%
% 저장 경로 바꾸는 법:
%   main_isl.m 맨 아래 saveRoot 한 줄만 수정
%     saveRoot = 'C:\Users\eun\Desktop\capstone_isl\baseline';   <- 본인 PC 경로로 변경
%   * 다른 PC에서는 C:\Users\eun 부분이 다르니 꼭 바꿔야 함
%   * 폴더가 없으면 자동으로 만들어짐
%   * 용량: 한 번 실행에 약 33 MB씩 쌓이니 필요 없는 날짜 폴더는 지워도 됨
%
% =====================================================================
% 4. 설정값 바꾸는 법
% =====================================================================
% config_isl.m 만 수정하면 됨 (다른 파일은 건드릴 필요 없음)
%   예) P.genRate = 60;      1초마다 생성하는 패킷 수
%       P.packetSize = 160;  패킷 크기 (Byte)
%       P.simTime = 600000;  총 시뮬레이션 시간 (step, 1 step = 1 ms -> 600000 = 10분)
%       P.k, P.X, P.Y        B 라우팅 가중치 / 임계값
% 수정 후 main_isl 다시 실행
% 모든 변수 설명은 variables_isl.m 참고
%
% =====================================================================
% 5. 파일 역할
% =====================================================================
% 직접 실행하는 파일
%   main_isl.m        시뮬레이션 실행 + 결과 저장  (① 이것부터)
%   show_results.m    저장된 결과를 MATLAB 창에 띄움 (② 결과 볼 때)
% 수정하는 파일
%   config_isl.m      모든 설정값
% 읽기용 파일
%   README_isl.m      이 안내문
%   variables_isl.m   변수 정리
% 자동으로 불리는 파일 (직접 실행 X)
%   run_isl_sim.m     시뮬레이션 1회 실행
%   route_B.m         B 라우팅 결정 (나중에 강화학습으로 교체할 부분)
%   build_grid.m      6x6 Grid 생성
%   compute_metrics.m 성능 지표 계산
%   animate_run.m     애니메이션 GIF 저장
%   plot_metrics.m    지표 비교 그래프 PNG 저장
%   plot_analysis.m   실행 분석 그래프 PNG 저장
%   viz_colors.m      그래프 색 모음
%   save_results.m    결과를 저장 경로로 복사
