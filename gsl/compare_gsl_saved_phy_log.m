function R=compare_gsl_saved_phy_log(packetCSV)
% Frozen-path replay: replace ONLY PHY mapping in a previously saved run.
% Not a new DDQN evaluation: decisions were made with the original model.
root=fileparts(mfilename('fullpath'));
if nargin<1, packetCSV=fullfile(root,'results_toolbox_phy','saved_path_replay','source_packets.csv'); end
old=readtable(packetCSV,'TextType','string');
assert(height(old)==36000 && all(old.packetID==(1:36000).'));
C=configGSLToolboxPHY(); C.makePlots=false; C.exportResults=false;
last=@(x)[x;x(end)];
L=table([old.time_s;C.duration_s],last(old.servingSatID),last(old.servingSatID>0), ...
    [logical(old.handover_event);false],last(old.servingElevation_deg), ...
    last(old.propagation_delay_ms),last(old.snr_dB), ...
    'VariableNames',{'time_s','servingSatID','isLinkAvailable','handoverEvent', ...
    'elevation_deg','propagationDelay_ms','snr_dB'});
P=evaluateGSLPackets(L,C,old.time_s,old.packetID,old.phyRandomDraw);
assert(isequal(P.snr_dB,old.snr_dB) && isequal(P.servingSatID,old.servingSatID) ...
    && isequal(double(P.handover_loss),double(old.handover_loss)));
A=computePacketMetrics(old,C.rollingWindow_s); B=computePacketMetrics(P,C.rollingWindow_s);
assert(B.pendingPackets==0 && B.generatedPackets-B.receivedPackets== ...
    B.phyLossPackets+B.handoverLossPackets+B.outageLossPackets);
summary=table(["Saved JPL run";"Toolbox PHY, frozen path"], ...
    [A.packetLossRatio;B.packetLossRatio],[A.onTimeDeliveryRate_pct;B.onTimeDeliveryRate_pct], ...
    [A.maxConsecutiveLoss;B.maxConsecutiveLoss],[A.phyLossPackets;B.phyLossPackets], ...
    [A.handoverLossPackets;B.handoverLossPackets], ...
    'VariableNames',{'model','loss_pct','onTime_pct','maxLossRun','phyLoss','handoverLoss'});
out=fullfile(root,'results_toolbox_phy','saved_path_replay'); if ~isfolder(out),mkdir(out);end
writetable(P,fullfile(out,'toolbox_packets.csv')); writetable(B.lossRuns,fullfile(out,'toolbox_loss_runs.csv'));
writetable(summary,fullfile(out,'comparison.csv'));
R=struct('summary',summary,'packetTable',P,'packetMetrics',B,'sourcePacketCSV',packetCSV);
save(fullfile(out,'replay.mat'),'R','-v7.3'); disp(summary);
end
