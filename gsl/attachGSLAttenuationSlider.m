function attachGSLAttenuationSlider(f,B)
% Controls live in the existing results window. Update on mouse release.
H=getappdata(f,'GSLPacketPlotHandles'); H.layout.OuterPosition=[0 0 1 .70];
setappdata(f,'GSLAttenuationReference',B.clear);
uicontrol(f,'Style','text','Units','normalized','Position',[.02 .855 .30 .025], ...
    'String','추가 감쇠 실험: 0~20 dB','BackgroundColor','w','HorizontalAlignment','left');
s=uicontrol(f,'Style','slider','Units','normalized','Position',[.32 .855 .43 .025], ...
    'Min',0,'Max',20,'Value',0,'SliderStep',[.005 .05], ...
    'Tag','GSLAttenuationSlider','Callback',@(src,~)updateGSLAttenuation(f,src.Value));
uicontrol(f,'Style','pushbutton','Units','normalized','Position',[.77 .85 .10 .035], ...
    'String','감쇠 적용','Callback',@(~,~)updateGSLAttenuation(f,s.Value));
uicontrol(f,'Style','pushbutton','Units','normalized','Position',[.88 .85 .10 .035], ...
    'String','결과 저장','Callback',@(~,~)saveGSLAttenuation(f));
uicontrol(f,'Style','text','Units','normalized','Position',[.02 .817 .96 .029], ...
    'String','작은 감쇠: 양호한 환경 → 큰 감쇠: 강우 등 신호 약화 예시. 특정 dB = 특정 날씨가 아닙니다.', ...
    'BackgroundColor','w','HorizontalAlignment','left','FontSize',10);
uicontrol(f,'Style','text','Units','normalized','Position',[.02 .725 .96 .09], ...
    'Tag','GSLAttenuationStatus','String','기존 날씨 비교 모드. 슬라이더를 놓거나 [감쇠 적용]을 누르면 별도 실험으로 전환합니다.', ...
    'BackgroundColor',[1 .97 .88],'HorizontalAlignment','left','FontSize',10);
end
