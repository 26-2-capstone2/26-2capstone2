function attachGSLAttenuationSlider(f,B)
% Slider value is total environment loss. Update on mouse release.
H=getappdata(f,'GSLPacketPlotHandles'); H.layout.OuterPosition=[0 0 1 .79];
setappdata(f,'GSLAttenuationReference',B.clear);
uicontrol(f,'Style','text','Units','normalized','Position',[.02 .958 .22 .027], ...
    'Tag','GSLEnvironmentValue','String','환경 감쇠량: 2.0 dB','BackgroundColor','w','HorizontalAlignment','left','FontSize',12);
s=uicontrol(f,'Style','slider','Units','normalized','Position',[.25 .958 .50 .027], ...
    'Min',0,'Max',20,'Value',2,'SliderStep',[.005 .05], ...
    'Tag','GSLAttenuationSlider','Callback',@(src,~)updateGSLAttenuation(f,src.Value));
uicontrol(f,'Style','pushbutton','Units','normalized','Position',[.77 .951 .10 .04], ...
    'String','감쇠 적용','Callback',@(~,~)updateGSLAttenuation(f,s.Value));
uicontrol(f,'Style','pushbutton','Units','normalized','Position',[.88 .951 .10 .04], ...
    'String','결과 저장','Callback',@(~,~)saveGSLAttenuation(f));
uicontrol(f,'Style','text','Units','normalized','Position',[.02 .915 .96 .03], ...
    'String','설명용 예시: 맑음 2 dB | 흐림 4 dB | 비 12 dB — 실측값·ITU 고정값이 아닌 실험 가정', ...
    'BackgroundColor','w','HorizontalAlignment','left','FontSize',10);
uicontrol(f,'Style','text','Units','normalized','Position',[.02 .807 .96 .10], ...
    'Tag','GSLAttenuationStatus','String','환경 감쇠량 계산 중', ...
    'BackgroundColor',[1 .97 .88],'HorizontalAlignment','left','FontSize',10);
end
